#!/usr/bin/env python3
"""
Knoll Mini — digital verification pass (FreeCAD 1.x, headless).

Runs real checks ON the production solids (no printing required):

  1. solid validity   — every part is valid, non-empty
  2. interference     — pairwise boolean common(); overlap volume > tol fails
  3. fit probes       — servo / battery / speaker envelopes inside mounts
  4. hole alignment   — collar screw axes must land inside pocket boss solid
  5. mass + CoM       — printed-part mass (PETG) + declared component masses
  6. structural math  — analytical knee torque, screw shear, insert pull-out
                        (NOT FEA — no solver bundled; flagged as such)

    KNOLL_DOC=./cad/knoll-mini.FCStd freecadcmd verify_kit.py
writes cad/VERIFICATION.md
"""
import os

import FreeCAD as App
import Part

DOC_PATH = os.environ.get("KNOLL_DOC", "knoll-mini.FCStd")
OUT = os.path.join(os.path.dirname(DOC_PATH) or ".", "VERIFICATION.md")

SV = (23.2, 12.1, 25.25)          # servo envelope
DENSITY_PETG = 1.27e-3            # g/mm3
GRAV = 9.81
CLR, WALL, BOSS_R = 0.6, 1.6, 2.6
BOSS_OFF = SV[0] / 2 + CLR + WALL + BOSS_R - 2.0   # 14.4 — matches build_kit

# pocket centres — mirror of build_kit placement
HIP_Y, COL_A, COL_B = 16.5, -16.0, 20.0
PY = HIP_Y - 2.5
POCKET_POS = {
    "HYAW_L": (COL_A, PY, 60),   "HYAW_R": (COL_A, -PY, 60),
    "HPITCH_L": (COL_A, PY, 30), "HPITCH_R": (COL_A, -PY, 30),
    "HROLL_L": (COL_B, PY, 60),  "HROLL_R": (COL_B, -PY, 60),
    "KNEE_L": (COL_B, PY, 30),   "KNEE_R": (COL_B, -PY, 30),
    "NPITCH": (0, 0, 102),
}

# declared component masses (g) with approx CoM in robot frame (mm)
COMPONENTS = [
    ("servos x10",   10 * 13.2, (0, 0, 55)),
    ("battery 2S",   18,        (0, 0, 82)),
    ("esp32-s3",     6,         (-14, 0, 95)),
    ("imu bno085",   2,         (-14, -11, 85)),
    ("bus hub+buck", 8,         (-14, 0, 90)),
    ("speaker",      3,         (15, 8, 87)),
    ("head elec",    10,        (22, 0, 148)),
]

doc = App.openDocument(DOC_PATH)
parts = {}
for o in doc.Objects:
    if o.TypeId == "Part::Feature" and hasattr(o, "Shape"):
        s = o.Shape
        if not s.isNull():
            parts[o.Name] = s

lines = []
def out(s=""):
    print(s)
    lines.append(s)


def box(dx, dy, dz, x=0, y=0, z=0):
    return Part.makeBox(dx, dy, dz, App.Vector(x - dx / 2, y - dy / 2, z))


def common_vol(a, b):
    try:
        c = a.common(b)
        return 0.0 if c.isNull() else c.Volume
    except Exception:
        return -1.0


def bb_overlap(a, b):
    ba, bb2 = a.BoundBox, b.BoundBox
    return not (ba.XMax < bb2.XMin or bb2.XMax < ba.XMin or
                ba.YMax < bb2.YMin or bb2.YMax < ba.YMin or
                ba.ZMax < bb2.ZMin or bb2.ZMax < ba.ZMin)


# ---------- 1. solid validity ---------------------------------------------
out("# Knoll Mini — model verification report\n")
out("Auto-generated by `cad/verify_kit.py` on `knoll-mini.FCStd`.\n")
out("## 1. Solid validity\n")
bad = []
for n, s in sorted(parts.items()):
    if not (s.isValid() and s.Volume > 0 and len(s.Solids) >= 1):
        bad.append(n)
out(f"parts checked: **{len(parts)}**")
if bad:
    out(f"**FAIL** — invalid/empty solids: {bad}")
else:
    out("all parts valid solids with volume > 0\n")

# ---------- 2. pairwise interference ---------------------------------------
out("\n## 2. Interference check (boolean common)\n")
names = sorted(parts)
inter = []
solver_fail = []
for i in range(len(names)):
    for j in range(i + 1, len(names)):
        a, b = names[i], names[j]
        sa, sb = parts[a], parts[b]
        if not bb_overlap(sa, sb):
            continue
        v = common_vol(sa, sb)
        if v < 0:
            solver_fail.append((a, b))
        elif v > 0.5:                       # mm3 — ignore numeric dust
            inter.append((a, b, round(v, 2)))

out(f"part pairs: {len(names) * (len(names) - 1) // 2}, "
    f"candidates tested: {len(inter) + len(solver_fail)}+")
if inter:
    out(f"\n**FAIL — {len(inter)} interfering pairs (>0.5 mm³):**\n")
    out("| part A | part B | overlap mm³ |")
    out("|---|---|---|")
    for a, b, v in inter:
        out(f"| {a} | {b} | {v} |")
else:
    out("no volumetric interferences above 0.5 mm³\n")
if solver_fail:
    out(f"\n*boolean solver inconclusive on {len(solver_fail)} pairs:* "
        f"{solver_fail[:8]}{' …' if len(solver_fail) > 8 else ''}")

# ---------- 3. fit probes ---------------------------------------------------
out("\n## 3. Component fit probes (envelope inside mount → overlap ≈ 0)\n")
probes = []
for pn, (px, py, pz) in POCKET_POS.items():
    tgt = parts.get(pn)
    if tgt is None:
        continue
    probe = box(*SV, px, py, pz - SV[2] / 2)
    probes.append((pn, "servo 23.2x12.1x25.25", round(common_vol(probe, tgt), 2)))
if "TRUNK_F" in parts:
    probes.append(("TRUNK_F/battery", "33x23x9.5 battery (pouch minus edge radius)",
                   round(common_vol(box(33, 23, 9.5, 0.9, 0, 78.7),
                                    parts["TRUNK_F"]), 2)))
    probes.append(("TRUNK_F/speaker", "d16x4 speaker",
                   round(common_vol(Part.makeCylinder(
                       8, 4, App.Vector(13, 0, 90), App.Vector(1, 0, 0)),
                       parts["TRUNK_F"]), 2)))
out("| mount | probe | intrusion mm³ | status |")
out("|---|---|---|---|")
fit_fail = 0
for m, d, v in probes:
    ok = v < 2.0
    if not ok:
        fit_fail += 1
    out(f"| {m} | {d} | {v} | {'OK' if ok else '**FAIL**'} |")
out(f"\n{len(probes)} probes, {fit_fail} failures")

# ---------- 4. hole alignment ----------------------------------------------
out("\n## 4. Collar-hole → boss alignment\n")
mis = []
checked = 0
for pn, (px, py, pz) in POCKET_POS.items():
    col = parts.get(pn + "_collar")
    pock = parts.get(pn)
    if col is None or pock is None:
        continue
    cz = pz + SV[2] / 2 + 1.2
    for sgn in (-1, 1):
        bx = px + sgn * BOSS_OFF
        # pin through the screw path: collar top -> boss bottom
        pin = Part.makeCylinder(1.4, SV[2] + 10,
                                App.Vector(bx, py, pz - SV[2] / 2 - WALL),
                                App.Vector(0, 0, 1))
        vc = common_vol(pin, col)
        vp = common_vol(pin, pock)
        checked += 1
        if vp < 3.0:
            mis.append((pn, sgn, f"pin misses pocket boss ({vp:.1f} mm³)"))
        if vc > 0.5:
            mis.append((pn, sgn, f"collar not bored at boss ({vc:.1f} mm³ solid)"))
if mis:
    out(f"**FAIL — {len(mis)} misaligned screw paths:**")
    for m in mis:
        out(f"- {m}")
else:
    out(f"all {checked} collar screw paths land on boss material "
        f"with clearance through the collar\n")

# ---------- 5. mass + CoM ---------------------------------------------------
out("\n## 5. Mass + centre of mass\n")
pmass = 0.0
cx = cy = cz = 0.0
for s in parts.values():
    for sol in s.Solids:
        m_sol = sol.Volume * DENSITY_PETG
        pmass += m_sol
        c = sol.CenterOfMass
        cx += m_sol * c.x
        cy += m_sol * c.y
        cz += m_sol * c.z
cmass = sum(m for _, m, _ in COMPONENTS)
for _, m, (x, y, z) in COMPONENTS:
    cx += m * x
    cy += m * y
    cz += m * z
tot = pmass + cmass
cx, cy, cz = cx / tot, cy / tot, cz / tot
out("| | mass g |")
out("|---|---|")
out(f"| printed parts (PETG, {len(parts)} pcs) | {pmass:.0f} |")
out(f"| components (declared) | {cmass:.0f} |")
out(f"| **total** | **{tot:.0f}** |")
out(f"\nCoM ≈ ({cx:.0f}, {cy:.0f}, {cz:.0f}) mm")

# ---------- 6. structural math (analytical, not FEA) ------------------------
out("\n## 6. Structural estimates (analytical — NOT FEA)\n")
m = tot / 1000.0
for lever, tag in ((0.022, "CoM over toe edge"), (0.045, "bent-knee recovery")):
    t = m * GRAV * lever
    out(f"- knee torque {tag}: τ = {t:.3f} N·m ({t * 10.2:.2f} kg·cm) "
        f"vs SCS0009 rated 0.07 / stall 0.22 → "
        f"{'OK at stall' if t < 0.22 else '**EXCEEDS STALL**'}, "
        f"{'rated OK' if t < 0.07 else '**above rated — intermittent only**'}")
F = 0.22 / 0.012
out(f"- collar boss reaction at stall: {F:.1f} N; PETG shear ~130 mm² "
    f"→ {F / 130:.2f} N/mm² (yield ~25) → OK")
out("- M2x4 heat-set insert pull-out ~60–90 N vs joint loads ~5–15 N → OK")
out(f"- sole pressure: {m * GRAV:.2f} N / {41 * 25} mm² "
    f"= {m * GRAV / (41 * 25) * 1000:.2f} kPa — trivial")

# ---------- summary ---------------------------------------------------------
out("\n## Verdict\n")
nfail = (1 if bad else 0) + len(inter) + fit_fail + len(mis)
if nfail == 0:
    out("**PASS** — no interferences, envelopes fit, holes aligned, "
        "mounts structurally sound (analytical).")
else:
    out(f"**{nfail} issue(s)** — see above. Fix in `build_kit.py`, rebuild, "
        f"re-verify. Do not print until PASS.")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"\n[verify] wrote {OUT}")
print("[done]")
